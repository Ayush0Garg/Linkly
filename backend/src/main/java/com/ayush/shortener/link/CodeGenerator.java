package com.ayush.shortener.link;

import java.util.List;
import java.util.Locale;

import com.ayush.shortener.config.AppProperties;
import org.springframework.stereotype.Component;
import org.sqids.Sqids;

/**
 * Turns a database sequence value into a short code: {prefix}{sqids(id)}, e.g. "linkly-KZrNBm".
 * Sqids is a reversible, collision-free encoding (unique id in => unique code out) with a shuffled alphabet, so the
 * random-looking part isn't sequential or trivially enumerable. That is obfuscation, not encryption: never rely on a
 * code being secret.
 * The prefix marks a code as generated by this service. Because custom aliases may not start with it, a generated code
 * can never collide with an alias.
 */
@Component
public class CodeGenerator {

    private static final int MAX_CODE_LENGTH = 32;

    private final Sqids sqids;
    private final String prefix;

    public CodeGenerator(AppProperties properties) {
        AppProperties.Code config = properties.code();
        if (config.alphabet() == null || config.alphabet().isBlank() || config.alphabet().contains("${")) {
            // Spring leaves an unresolved ${CODE_ALPHABET} as literal text; say what is wrong instead of letting Sqids complain
            throw new IllegalStateException("app.code.alphabet (CODE_ALPHABET) is not set. Production must provide its own "
                    + "shuffled alphabet and never change it afterwards (see DEPLOY.md).");
        }
        this.prefix = config.prefix() == null ? "" : config.prefix();
        if (!prefix.matches("[A-Za-z0-9_-]*") || prefix.length() + config.minLength() > MAX_CODE_LENGTH) {
            throw new IllegalStateException("app.code.prefix must be URL-safe and leave room for the generated part");
        }
        this.sqids = Sqids.builder()
                .alphabet(config.alphabet())
                .minLength(config.minLength())
                .build();
    }

    public String encode(long id) {
        return prefix + sqids.encode(List.of(id));
    }

    /** True if a user-chosen alias would be mistaken for a generated code (case-insensitive, to stop lookalikes). */
    public boolean usesReservedPrefix(String alias) {
        return !prefix.isEmpty() && alias.toLowerCase(Locale.ROOT).startsWith(prefix.toLowerCase(Locale.ROOT));
    }
}
